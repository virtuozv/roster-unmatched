let lang = localStorage.getItem("rosterLang") === "en" ? "en" : "ru";
const listeners = new Set();

export function getLang() {
  return lang;
}

export function t(key, vars) {
  const table = STRINGS[lang] || STRINGS.ru;
  let text = table[key] ?? STRINGS.ru[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach((name) => {
      text = text.split("{" + name + "}").join(String(vars[name]));
    });
  }
  return text;
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function setLang(next) {
  lang = next === "en" ? "en" : "ru";
  localStorage.setItem("rosterLang", lang);
  document.documentElement.lang = lang === "en" ? "en" : "ru";
  applyDom();
  listeners.forEach((fn) => fn(lang));
}

export function startI18n() {
  document.documentElement.lang = lang === "en" ? "en" : "ru";
  const rus = document.getElementById("langRu");
  const eng = document.getElementById("langEn");
  if (rus) {
    rus.addEventListener("click", () => setLang("ru"));
  }
  if (eng) {
    eng.addEventListener("click", () => setLang("en"));
  }
  applyDom();
}

function applyDom() {
  document.title = t("titleDoc");
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (key) {
      node.textContent = t(key);
    }
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.getAttribute("data-i18n-placeholder");
    if (key) {
      node.setAttribute("placeholder", t(key));
    }
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const key = node.getAttribute("data-i18n-aria");
    if (key) {
      node.setAttribute("aria-label", t(key));
    }
  });
  const rus = document.getElementById("langRu");
  const eng = document.getElementById("langEn");
  if (rus) {
    rus.classList.toggle("is-on", lang === "ru");
  }
  if (eng) {
    eng.classList.toggle("is-on", lang === "en");
  }
}
